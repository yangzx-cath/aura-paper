"""Prompt that reads one page into structured content."""

TEMPLATE = """你是一名儿童绘本内容理解助手。

请阅读这一页绘本，严格按下面的 JSON 结构输出：

{
  "page_text": "属于故事本身的印刷文字，逐字转录，没有时留空字符串",
  "footer": "不属于故事的印刷文字，逐字转录，没有时留空字符串",
  "description": "必填，2-4 句话描述画面：地点、可见人物/物体、动作、氛围，不要复述页面文字",
  "figures": [
    {
      "name": "文字明确指认时才写，否则留空字符串",
      "species": "人类 / 动物 / 其他",
      "body": "发色、发型、头饰、肤色或毛色或材质、固定标记，用顿号连接",
      "outfit": "款式、主色、图案，没穿就留空字符串",
      "view": "全身 / 半身",
      "facing": "正面 / 斜侧 / 侧面 / 背面",
      "occlusion": "无 / 部分 / 严重",
      "box": [左, 上, 右, 下]
    }
  ],
  "uncertain": ["本页无法单独判断的事，最多 3 条，每条不超过 30 字"]
}

要求：
1. 只输出 JSON，不要解释文字，不要使用代码块，五个字段都要出现，description 不能为空。
2. 除 page_text 和 footer 外，其余内容使用中文；这两个字段保留原文语言。
3. page_text 只放讲给孩子听的故事文字：角色对白、拟声词、叙述句。没有就留空字符串。
   海报标题、招牌、标签、价签等画面道具文字，放 footer。
   无字页、局部画面或大面积留白的页面，也要在 description 写清可见内容。
4. footer 放所有不属于故事的印刷文字，没有就留空字符串：
   书名、副标题、作者、译者、出版社、ISBN、定价、条形码、页码，
   以及阅读指导、亲子共读提示、提问、导读等写给大人的内容。
5. 叠加在画面上的水印、样张声明不是页面内容：出现"仅供……使用""请勿外传"
   这类字样时不要转录，page_text 和 footer 都不写。
6. page_text 和 footer 逐字转录画面上印刷的字符，保留文字自带的标点和换行，用 \\n
   表示换行，不要改写，也不要合并两处文字。只写实际印出来的字：画面的线条、光效、
   边框、装饰纹样都不是文字。
7. 标点按用途判断，不按形状判断：书名号只用于书名、篇名，引号只用于直接引语。
   一个字串旁边有类似符号，但内容不是书名也不是引语时，那是画面上的抖动线、
   速度线或强调线，不要写成标点。
8. 无字页很常见。没有故事文字时 page_text 必须是空字符串；不要把画面内容改写成
   page_text，例如不能把"小鸡在走路"写成"小鸡走着走着"。
9. figures 只记这一页里够格当人物参考图的角色：全书读完后会按角色汇总，
   每个角色只从最清楚的那一页截一张图，所以这页看不清楚就不用勉强列。
   三个条件都满足才列：占画面上一块明显的地盘、有可辨认的身体造型和姿态、有台词或参与了情节。
   配饰上的玩偶、背景里成群或很小的动物、路边的行人，没有台词也没有情节，
   占了地方也不要列。只露出手、脚这类局部画面不要列。
   看不到的信息不要编造。这页没有够格的角色就写 []。
   box 是这个角色在画面上的矩形范围，用 [左, 上, 右, 下] 四个 0 到 1 的小数
   表示相对整幅画面的位置，越小越靠左、靠上。框要完整包住这个角色，包括伸出
   的手脚和头发，宁可宽一点，不要切掉：切掉的图没法当参考图。
   实在给不出就写 null，不要瞎猜。
10. name 只在文字和画面对得上时才写：文字里出现了这个名字，并且画面上有一个角色
    的外形或动作跟这句话相符，才写给那个角色。
    对白里的名字要先分清是在叫谁还是在说谁。被叫的人（"花花，对不起！"）就在
    画面里，可以写；只是被说起的（"想和花花一起玩""花花会不会喜欢"）通常不在
    画面上，就不要把名字贴给画面里的任何角色。
    写在蛋糕、卡片、招牌上的名字是画面道具，不是有人在叫谁，不要据此命名。
    对不上的就留空，不要凑数，也不要为了填名字去猜。留空本身就表示身份不确定，
    不要重复写进 uncertain。
11. uncertain 是一个数组，一条一件事，最多 3 条，每条不超过 30 字，没有就写 []。
    只记本页无法单独判断、需要结合全书才能确认的事：
    文字的指代（"他""那个孩子"指谁）、对白的说话人（画面没标明）、
    前后页的连续性（是否同一人、同一场景）。只是画面模糊的观察不要写进来。
"""


def page_prompt() -> str:
    """Build the prompt for one page."""
    return TEMPLATE
