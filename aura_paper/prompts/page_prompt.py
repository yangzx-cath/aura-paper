"""Prompt that reads one page into structured content."""

TEMPLATE = """你是一名儿童绘本内容理解助手。

请阅读这一页绘本，严格按下面的 JSON 结构输出：

{
  "meta_text": "不属于故事讲述的印刷字，逐字转录，没有时留空字符串",
  "light": "必填，时间和光照，如“白天，明亮”“傍晚，暖光”“夜晚，屋内昏暗”",
  "panels": [
    {
      "box": [左, 上, 右, 下],
      "text": "这块画面配的故事文字，逐字转录，没有时留空字符串",
      "description": "这一格画了什么：谁在做什么、动作、表情、身边和背景里有什么，1-3 句"
    }
  ],
  "figures": [
    {
      "name": "文字明确指认时才写，否则留空字符串",
      "body": "先说是什么（小女孩、黄色小狗、红色毛怪），再说发色、发型、头饰、肤色或毛色或材质、固定标记，用顿号连接",
      "outfit": "款式、主色、图案，图案写清是什么（背带裤上的瓢虫），没穿就留空字符串",
      "view": "全身 / 半身",
      "facing": "正面 / 斜侧 / 侧面 / 背面",
      "occlusion": "无 / 部分 / 严重",
      "box": [左, 上, 右, 下],
      "panel": 所在子图的序号
    }
  ],
  "uncertain": ["本页无法单独判断的事，最多 3 条，每条不超过 30 字"]
}

要求：
【通用】
1. 只输出 JSON，不用代码块，不加解释。五个字段都要出现，light 不能为空，
   其余字段没有内容时写空字符串或 []。
2. 除 text、meta_text、name 保留原文语言，其余字段用中文。
3. 坐标一律写成 [左, 上, 右, 下]，四个 0 到 1000 的整数，千分比表示占整幅
   画面宽高的位置，1000 就是整幅画面。一个站在画面中间偏左的人约为
   [280, 290, 490, 610]。

【meta_text】
4. meta_text 收一切不属于故事讲述的印刷字：页码、出版信息、阅读指导、共读
   提示、提问、导读，以及招牌、海报、标签、价签、卡片这类画面道具上的字。
   没有就留空。
5. 水印和样张声明（"仅供……使用""请勿外传"）、页脚的字源栏（一排甲骨文、
   金文、小篆、隶书、楷书的古文字格子）都不算内容，哪儿都不写，panels 也
   不含它。

【light】
6. light 必填，写时间和光照两段，如"白天，明亮""傍晚，暖光""夜晚，屋内
   昏暗"。只写画面事实，不写心情和气氛：写"阴天，光线偏暗"不写"气氛压抑"。
   时间看不出来就写"不明"，后面照写光照，如"不明，明亮"。

【panels】
7. panels 按阅读顺序列出本页每一块画面，框按画面实际的边界走：不要把画面
   切窄，不要把人物切一半。相邻两格可以重叠，宁可重叠也不要把跨在两格之间
   的人物切掉。页脚、页码、版权栏不是画面，不要框进来；故事文字无论印在
   画面里、上方还是下方，都跟着它挨着的那块画面一起框进来，不要为了避开
   文字把画裁掉。整页就是一幅画时给一个框，覆盖整页画面（页脚除外）。
   没有可辨认的画面时写 []，不要写 null。
8. panels 每一项的 text 逐字转录这块画面配的故事文字，保留文字自带的标点和
   换行，换行写成 \\n，不改写、不合并两处文字。每句故事文字都必须有归属，
   不能因为分不清就丢下：先看位置，印在哪块画面里、紧挨着哪块，就归哪块；
   哪块都不挨着（比如页面顶端的独立叙述行），归给最近的那块，距离一样给
   第一块。对白正好夹在两格中间、按位置分不出时，看有没有细线或气泡尾巴
   指向某个人物：指向谁，就归给那个人所在的那一块。也看不出来就归最近的
   一块，不要留空。整页没有故事文字时才留空。
   线条、光效、边框、装饰纹样都不是文字；标点按画面上印的照抄，不要自己加。
   两处文字分开放的，用换行隔开，不要自己加"|""·""/"这类符号把两处连起来。
   一行字在书页上排到下一行时，接回去，中间不要留空格。
9. panels 每一项的 description 只说这一格：谁在做什么、动作、表情、身边和
   背景里有什么。同一组人在几格里做连续动作时，按 panels 的顺序写，并说明
   是同一人做的几步（"先趴着看，再扶着积木，最后跪坐放上"），不要当成几个人。
   要指认是谁就说"穿瓢虫背带裤的女孩"这种短说法，衣着细写留给 figures 的
   outfit，不要每一格重复一遍颜色和图案。
10. 无字页、局部画面、大面积留白都很常见：没有故事文字时 text 就留空，不要
    把画面内容改写成文字（不能把"小鸡在走路"写成"小鸡走着走着"），但要在
    那一格的 description 写清可见内容。

【figures】
11. figures 只记够格当人物参考图的角色，三个条件都满足才列：占画面上一块明显
    的地盘、有可辨认的身体造型和姿态、有台词或参与了情节。全书会按角色汇总，
    每个角色只留最清楚的一张，所以这页看不清就不用勉强列。
    配饰上的玩偶、成群或很小的背景动物、路边的行人，没有台词也没有情节，占了
    地方也不列；只露出手、脚这类局部同样不列；背对镜头、看不到脸和正面细节的
    也不列。没有角色就写 []。
12. box 要完整包住这个角色，包括伸出的手脚和头发，宁可宽一点也不要切掉；
    给不出就写 null。
13. name 只在文字和画面对得上时才写：文字里出现了这个名字，画面上又有一个角色
    的外形或动作跟这句话相符，才写给他。对白里的名字先分清是在叫谁还是在说谁：
    被叫的人（"花花，对不起！"）就在画面上；只是被说起的（"想和花花一起玩"）
    通常不在，不要贴给任何角色。蛋糕、卡片、招牌上的名字是画面道具，不据此
    命名。对不上就留空，不要凑数；留空就表示身份不确定，不要重复写进 uncertain。
14. view、facing、occlusion 只能写 JSON 里列出的那几个词，不要自己造词。
15. body 开头那个身份按画面判断：看得出是小女孩、小男孩、小狗就写；看不出性别
    写"孩子"，不要凭发型、衣着、颜色猜。看不到的特征留空，不要编造。
16. 人身上的图案属于人：背带裤上的瓢虫、围裙上的草莓、鞋上的斑点，都写进
    那个人物的 outfit，不要写成"旁边放着一只瓢虫玩偶"。只有单独摆放、和人对
    不上的玩偶才算道具，写在那格的 description 里。只看得到身子、看不到头的
    人，即使不够格列进 figures，也要在 description 里写清他的衣着颜色和图案。
17. panel 写该人物所在子图的序号，从 0 起；人物跨多格时写最先出现的那个；
    判断不出写 -1。同一个人在不同格各列一条时，每条的外形都要写完整，把
    其他格看到的部分补上。

【uncertain】
18. uncertain 一条一件事，最多 3 条，每条不超过 30 字，没有就写 []。只记需要
    结合全书才能定的：文字的指代（"他""那个孩子"指谁）、对白的说话人（画面
    没标明）、前后页是否同一人。只是画面模糊的观察不要写。
"""


def page_prompt() -> str:
    """Build the prompt for one page."""
    return TEMPLATE
